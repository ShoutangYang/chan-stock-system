# 港股：5 位数字（允许 1-5 位输入后补齐）
_HK_RE = re.compile(r"^\d{1,5}$")


def detect_market(symbol: str) -> str:
    """根据代码形态判断市场。"""
    s = (symbol or "").strip().upper()
    if not s:
        return US
    # 显式后缀
    if s.endswith(".HK"):
        return HK
    # 常见前缀写法
    for p in ("HK", "HK:", "HK."):
        if s.startswith(p) and s[len(p):].strip().isdigit():
            return HK
    body = s.split(".")[0]
    if _HK_RE.match(body):
        return HK
    return US


def normalize(symbol: str, market: Optional[str] = None) -> Tuple[str, str]:
    """
    返回 (market, code)。
        ("00700")       -> ("HK", "00700")
        ("700.HK")      -> ("HK", "00700")
        ("HK00700")     -> ("HK", "00700")
        ("aapl")        -> ("US", "AAPL")
    """
    s = (symbol or "").strip().upper()
    m = market or detect_market(s)
    if m == HK:
        s = re.sub(r"^(HK[:.]?)", "", s)
        s = s.replace(".HK", "")
        s = re.sub(r"\D", "", s)
        if not s:
            return HK, ""
        return HK, s.zfill(5)
    return US, s


def display(symbol: str, market: Optional[str] = None) -> str:
    """展示用代码：港股补 .HK，美股原样。"""
    m, code = normalize(symbol, market)
    return code + MARKET_META[m]["suffix"] if code else code


def money(v, market: str = US) -> str:
    """按市场货币符号格式化。"""
    if v is None:
        return "—"
    try:
        return MARKET_META[market]["currency_symbol"] + f"{float(v):,.2f}"
    except (TypeError, ValueError):
        return "—"


