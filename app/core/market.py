def hk_stock_symbols() -> List[str]:
    return [c for c, *_ in HK_UNIVERSE]


def hk_etf_symbols() -> List[str]:
    return [c for c, *_ in HK_ETFS]


def hk_meta() -> Dict[str, Tuple[str, str]]:
    """代码 -> (中文名, 行业)"""
    return {c: (n, ind) for c, n, ind in HK_UNIVERSE}


def hk_etf_meta() -> Dict[str, Tuple[str, str, str]]:
    return {c: (n, k, d) for c, n, k, d in HK_ETFS}


def hk_industries() -> List[str]:
    out, seen = [], set()
    for _, _, ind in HK_UNIVERSE:
        if ind not in seen:
            seen.add(ind)
            out.append(ind)
    return out


